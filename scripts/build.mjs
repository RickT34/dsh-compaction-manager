// Concatenate src/client/*.js into the browser module format the Web app loads.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const parts = ['i18n.js', 'base.js', 'pipeline-editor.js', 'forms.js', 'page.js'];
let body = '';
for (const part of parts) body += `// ---- ${part}\n${await readFile(new URL(`src/client/${part}`, root), 'utf8')}\n`;
const out = `// Generated by scripts/build.mjs; edit src/client/*.js instead.
window.__ModuleLoader__.load({
  id: 'dsh-compaction-manager',
  factory: function (require) {
    'use strict';
    const React = require('react');
    const h = React.createElement;
${body}
    return { inject, apply };
  },
});
`;
await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/client.js', root), out);
console.log(`Built ${fileURLToPath(new URL('dist/client.js', root))}`);
